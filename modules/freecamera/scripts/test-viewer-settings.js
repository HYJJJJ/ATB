import assert from 'node:assert/strict';
import net from 'node:net';
import path from 'node:path';
import { mkdtemp, mkdir, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { chromium } from 'playwright';
import { startServers } from '../../../server/index.js';
import { loginViewer } from './account-test-helper.js';

const directory = await mkdtemp(path.join(tmpdir(), 'freecamera-viewer-settings-'));
await mkdir('test-results/viewer-settings', { recursive: true });
const listener = net.createServer(); await new Promise(r => listener.listen(0, '127.0.0.1', r));
const port = listener.address().port; await new Promise(r => listener.close(r));
let service = await startServers({ lanIp: '127.0.0.1', httpsPort: port, httpPort: 0, relayPort: 0, certDir: path.join(directory, 'certs'), dataDir: path.join(directory, 'data') });
const origin = `https://127.0.0.1:${port}`;
let browser;
try {
  browser = await chromium.launch({ args: ['--use-fake-device-for-media-stream', '--use-fake-ui-for-media-stream', '--autoplay-policy=no-user-gesture-required'] });
  const context = await browser.newContext({ ignoreHTTPSErrors: true, permissions: ['camera', 'microphone', 'notifications'] });
  const camera = await context.newPage(), viewer = await context.newPage();
  await camera.goto(`${origin}/?mode=camera`); await camera.locator('#start').click();
  await viewer.goto(`${origin}/?mode=viewer`); await loginViewer(viewer);
  await viewer.locator('#camera-list .device-connect').click();
  await viewer.waitForFunction(() => document.querySelector('#status').textContent === '实时画面' && !document.querySelector('#listen').disabled);
  await viewer.locator('#listen').click();
  await viewer.locator('#volume').fill('37');
  await viewer.locator('#notifications').check();
  await viewer.locator('#detection-toggle').check();
  await viewer.waitForFunction(() => document.querySelector('#detection-status').textContent.includes('运行中'));
  await viewer.reload();
  await viewer.waitForFunction(() => document.querySelector('#status').textContent === '实时画面');
  assert.equal(await viewer.locator('#listen').getAttribute('aria-pressed'), 'true', 'listening must survive re-entering the viewer');
  assert.equal(await viewer.locator('#volume').inputValue(), '37');
  assert.equal(await viewer.locator('#notifications').isChecked(), true);
  await viewer.waitForFunction(() => document.querySelector('#detection-status').textContent.includes('运行中'));
  const second = await context.newPage(); await second.goto(`${origin}/?mode=viewer`);
  await second.waitForFunction(() => document.querySelector('#status').textContent === '实时画面');
  await second.locator('#detection-toggle').uncheck();
  await viewer.waitForFunction(() => !document.querySelector('#detection-toggle').checked && document.querySelector('#detection-status').textContent.includes('已关闭'));
  await second.close();
  await viewer.locator('#detection-toggle').check();
  await viewer.waitForFunction(() => document.querySelector('#detection-status').textContent.includes('运行中'));
  await context.setOffline(true);
  await service.close(); service = null;
  await context.setOffline(false);
  service = await startServers({ lanIp: '127.0.0.1', httpsPort: port, httpPort: 0, relayPort: 0, certDir: path.join(directory, 'certs'), dataDir: path.join(directory, 'data') });
  await viewer.waitForFunction(() => document.querySelector('#status').textContent === '实时画面' && document.querySelector('#detection-status').textContent.includes('运行中'), null, { timeout: 30000 });
  assert.equal(await viewer.locator('#detection-toggle').isChecked(), true);
  assert.equal(await viewer.locator('#listen').getAttribute('aria-pressed'), 'true');
  assert.equal(await viewer.locator('#volume').inputValue(), '37');
  assert.equal(await viewer.locator('#notifications').isChecked(), true);
  await viewer.locator('#detection-toggle').uncheck();
  await viewer.waitForFunction(() => document.querySelector('#detection-status').textContent.includes('已关闭'));
  await viewer.locator('#listen').click(); await viewer.locator('#notifications').uncheck();
  await viewer.locator('#auto-connect').uncheck(); await viewer.reload();
  assert.equal(await viewer.locator('#auto-connect').isChecked(), false);
  assert.equal(await viewer.locator('#volume').inputValue(), '37');
  assert.equal(await viewer.locator('#notifications').isChecked(), false);
  await viewer.locator('#camera-list .device-connect').click();
  await viewer.waitForFunction(() => document.querySelector('#status').textContent === '实时画面');
  assert.equal(await viewer.locator('#listen').getAttribute('aria-pressed'), 'false');
  assert.equal(await viewer.locator('#detection-toggle').isChecked(), false);
  await viewer.screenshot({ path: 'test-results/viewer-settings/restored.png', fullPage: true });
  await writeFile('test-results/viewer-settings/report.json', JSON.stringify({ passed: true, time: new Date().toISOString(), checks: ['listen/volume/notifications survive reload', 'detection resumes after last-viewer reload', 'shared disable wins', 'server restart restores detection intent', 'network reconnect restores sound', 'explicit off and auto-connect off persist'] }, null, 2));
  console.log('PASS: viewer preferences, shared model intent, reload, network recovery, service restart and explicit off');
} finally { await browser?.close(); await service?.close(); await rm(directory, { recursive: true, force: true, maxRetries: 5, retryDelay: 200 }); }
