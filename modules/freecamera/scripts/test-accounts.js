import assert from 'node:assert/strict';
import net from 'node:net';
import path from 'node:path';
import { tmpdir } from 'node:os';
import { mkdtemp, mkdir, rm, writeFile } from 'node:fs/promises';
import { chromium } from 'playwright';
import { startServers } from '../../../server/index.js';
import { loginViewer } from './account-test-helper.js';
const credentials = { username: ' 家里 👀 ', password: '1' };
async function port() { const server = net.createServer(); await new Promise(resolve => server.listen(0, '127.0.0.1', resolve)); const value = server.address().port; await new Promise(resolve => server.close(resolve)); return value; }
const dir = await mkdtemp(path.join(tmpdir(), 'freecamera-accounts-ui-'));
const httpsPort = await port(), httpPort = await port();
const options = { relayPort: 0, lanIp: '127.0.0.1', httpsPort, httpPort, certDir: path.join(dir, 'certs'), dataDir: path.join(dir, 'data') };
let service = await startServers(options);
const browser = await chromium.launch({ args: ['--use-fake-device-for-media-stream', '--use-fake-ui-for-media-stream', '--mute-audio'] });
await mkdir('test-results/accounts', { recursive: true });
try {
  const context = await browser.newContext({ ignoreHTTPSErrors: true, permissions: ['camera', 'microphone'], acceptDownloads: true });
  const base = `https://127.0.0.1:${httpsPort}`, errors = [];
  const camera1 = await context.newPage(), camera2 = await context.newPage(), viewer = await context.newPage();
  for (const page of [camera1, camera2, viewer]) page.on('pageerror', error => errors.push(error.message));
  await camera1.goto(`${base}/?mode=camera`); await camera1.locator('#camera-name').fill('客厅 iPhone'); await camera1.locator('#start').click();
  await camera1.waitForFunction(() => /^\d{8}$/.test(document.querySelector('#pair-code').textContent));
  await camera2.goto(`${base}/?mode=camera`); await camera2.evaluate(() => localStorage.removeItem('freecamera.camera')); await camera2.reload();
  await camera2.locator('#camera-name').fill('门口 <camera>'); await camera2.locator('#start').click();
  await camera2.waitForFunction(() => /^\d{8}$/.test(document.querySelector('#pair-code').textContent));
  await viewer.goto(`${base}/?mode=viewer`);
  assert.equal(await viewer.locator('#auth-panel').isVisible(), true);
  assert.equal(await viewer.locator('#view-workspace').isVisible(), false);
  await loginViewer(viewer, credentials);
  assert.equal(await viewer.locator('#account-name').textContent(), `${credentials.username} · 管理员`);
  await viewer.waitForFunction(() => document.querySelectorAll('.device-item').length === 2);
  const entries = viewer.locator('.device-item');
  const firstEntry = entries.filter({ hasText: '客厅 iPhone' }), secondEntry = entries.filter({ hasText: '门口 <camera>' });
  assert.match(await firstEntry.textContent(), /客厅 iPhone.*在线/);
  assert.equal(await viewer.locator('#camera-list camera').count(), 0, 'camera names must be rendered as text');
  await firstEntry.locator('.device-connect').click();
  await viewer.waitForFunction(() => document.querySelector('#status').textContent === '实时画面');
  assert.equal(await viewer.locator('#device-name').textContent(), '客厅 iPhone');
  await firstEntry.locator('.device-remark').click({ timeout: 3000 }); await viewer.locator('#remark-input').fill('客厅 <主机>');
  await camera2.locator('#stop').click(); await secondEntry.getByText(/离线/).waitFor();
  assert.equal(await viewer.locator('#remark-input').inputValue(), '客厅 <主机>', 'live directory updates must preserve the remark being edited');
  await viewer.locator('#remark-save').click(); await viewer.waitForFunction(() => document.querySelector('#device-name').textContent === '客厅 <主机>');
  assert.equal(await viewer.locator('#camera-list 主机').count(), 0, 'remarks must render as text');
  assert.match(await entries.first().textContent(), /客厅 <主机>/, 'online cameras must precede offline devices');
  await camera2.locator('#start').click();
  await secondEntry.locator('.device-connect').click();
  await viewer.waitForFunction(() => document.querySelector('#device-name').textContent === '门口 <camera>' && document.querySelector('#status').textContent === '实时画面');
  await camera2.locator('#stop').click();
  await viewer.waitForFunction(() => [...document.querySelectorAll('.device-item')].some(item => item.textContent.includes('门口 <camera>') && item.textContent.includes('离线')));
  await viewer.locator('#disconnect').click();
  await secondEntry.locator('.device-connect').click();
  await viewer.waitForFunction(() => document.querySelector('#status').textContent === '等待摄像头上线');
  await camera2.locator('#start').click();
  await viewer.waitForFunction(() => document.querySelector('#status').textContent === '实时画面');
  await viewer.reload(); await viewer.waitForFunction(() => document.querySelector('#status').textContent === '实时画面');
  assert.match(await firstEntry.textContent(), /客厅 <主机>/, 'shared remark must survive page reload');
  const cookies = await context.cookies(base); assert.ok(cookies.some(cookie => cookie.name === '__Host-freecamera' && cookie.httpOnly && cookie.secure));
  await viewer.screenshot({ path: 'test-results/accounts/list.png', fullPage: true });
  const another = await context.newPage(); another.on('pageerror', error => errors.push(error.message));
  await another.goto(`${base}/?mode=viewer`); await another.waitForFunction(() => document.querySelector('#status').textContent === '实时画面');
  await viewer.locator('#logout').click();
  await viewer.waitForFunction(() => !document.querySelector('#auth-panel').hidden);
  await another.waitForFunction(() => !document.querySelector('#auth-panel').hidden);
  assert.equal(await another.locator('video').evaluate(video => video.srcObject), null);
  await viewer.locator('#auth-username').fill('admin'); await viewer.locator('#auth-password').fill('incorrect'); await viewer.locator('#auth-submit').click();
  await viewer.waitForFunction(() => document.querySelector('#auth-error').textContent.includes('不正确'));
  await loginViewer(viewer, credentials);
  await service.close(); service = null;
  await viewer.waitForFunction(() => document.querySelector('#catalog-status').textContent.includes('重连'));
  service = await startServers(options);
  await viewer.waitForFunction(() => document.querySelectorAll('.device-item').length === 2 && document.querySelector('#status').textContent === '实时画面');
  assert.deepEqual(errors, []);
  await writeFile('test-results/accounts/report.json', JSON.stringify({ passed: true, time: new Date().toISOString(), checks: ['local administrator setup', 'login gate', 'all-camera directory', 'direct selection and switching', 'safe camera name rendering', 'live online/offline list', 'offline waiting and reconnect', 'session reload', 'logout revokes all session windows', 'wrong-password rejection', 'restart resumes session and video without reload'] }, null, 2));
  console.log('PASS: administrator setup/login, live camera directory, direct switching, offline waiting, safe names, logout/expiry, restart and persistence');
} finally { await browser.close(); await service?.close(); await rm(dir, { recursive: true, force: true }); }
