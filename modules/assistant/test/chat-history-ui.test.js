import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,rm,readFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {chromium} from 'playwright';
import {startServers} from '../../../server/index.js';
import {SESSION_COOKIE} from '../../../server/accounts.js';

test('widget and main share recent history, context, clearing and reload without replaying speech',async t=>{
  const dir=await mkdtemp(path.join(tmpdir(),'atb-chat-history-'));
  const server=await startServers({lanIp:'127.0.0.1',httpsPort:0,httpPort:0,relayPort:0,publicOrigin:null,dataDir:path.join(dir,'data'),certDir:path.join(dir,'certs')});
  let browser;
  t.after(async()=>{await browser?.close();await server.close();await rm(dir,{recursive:true,force:true});});
  await server.accounts.setup('history-test','fixture-password');const session=await server.accounts.login('history-test','fixture-password');
  browser=await chromium.launch();const context=await browser.newContext({ignoreHTTPSErrors:true});
  await context.addCookies([{name:SESSION_COOKIE,value:session.token,domain:'127.0.0.1',path:'/',secure:true,httpOnly:true,sameSite:'Strict'}]);
  const origin='https://127.0.0.1:'+server.secure.address().port;
  assert.equal((await context.request.post(origin+'/api/assistant/settings',{headers:{origin},data:{scope:'all',name:'测试助手',prompt:'测试角色',memory:'',memoryMode:'off',provider:'custom',baseUrl:'https://fixture.example/v1',model:'fixture',apiKey:'fixture-key'}})).status(),200);
  const submitted=[],errors=[];let late;
  await context.route('**/api/assistant/chat',async route=>{
    const body=route.request().postDataJSON();submitted.push(body);
    const text=body.messages.at(-1).content;
    if(text==='接口拒绝'){await route.fulfill({status:502,contentType:'application/json',body:JSON.stringify({error:'模型工具调用达到限制'})});return;}
    if(['等待中的旧请求','等待中的失败'].includes(text))await new Promise(resolve=>{late=resolve;});
    const events=['失败的搜索','等待中的失败'].includes(text)?[{type:'delta',text:'未完成的半句'},{type:'error',error:'模拟搜索失败'}]:[{type:'delta',text:'回复：'+text},{type:'done',reply:'回复：'+text}];
    if(text==='摆件的第一句话')events.unshift({type:'tool',name:'weather',ok:true,sources:[{source:'测试天气来源',url:'https://example.com/weather'}]});
    await route.fulfill({contentType:'application/x-ndjson',body:events.map(event=>JSON.stringify(event)+'\n').join('')}).catch(()=>{});
  });
  for(const script of ['assistant.js','companion.js'])await context.route('**/'+script,async route=>route.fulfill({contentType:'text/javascript',body:await readFile(path.resolve('modules/assistant/public',script),'utf8')+'\nwindow.testSend=sendMessage;'}));
  const widget=await context.newPage();widget.on('pageerror',e=>errors.push(e.message));
  await widget.addInitScript(()=>{window.voiceCalls=[];window.atbCompanion={onEvent(){},call:async(action,options)=>{if(action==='voice')window.voiceCalls.push(options.action);return action==='settings'?{enabled:true,showText:true,reminders:false}:{};}};});
  const send=(page,text)=>page.evaluate(async text=>{try{return await window.testSend(text,{onDelta(){}});}catch(error){return {error:error.message};}},text);
  await widget.goto(origin+'/modules/assistant/companion.html');await widget.waitForFunction(()=>document.documentElement.dataset.account==='history-test'&&window.testSend);
  await send(widget,'摆件的第一句话');
  const main=await context.newPage();main.on('pageerror',e=>errors.push(e.message));
  await main.goto(origin+'/modules/assistant/#assistant');await main.waitForFunction(()=>!document.querySelector('#workspace').hidden&&window.testSend);
  await main.locator('#toggle-transcript').click();await main.locator('#transcript').waitFor({state:'visible'});
  await main.waitForFunction(()=>document.querySelector('#messages').textContent.includes('回复：摆件的第一句话'),null,{timeout:5000});
  assert.match(await main.locator('#messages .tool-sources').textContent(),/测试天气来源/,'tool sources follow the shared assistant reply');
  await send(main,'主界面接着聊');
  assert.deepEqual(submitted.at(-1).messages,[{role:'user',content:'摆件的第一句话'},{role:'assistant',content:'回复：摆件的第一句话'},{role:'user',content:'主界面接着聊'}]);
  await send(widget,'摆件继续聊');
  assert.equal(submitted.at(-1).messages.some(m=>m.content==='回复：主界面接着聊'),true,'reverse context sync');
  await main.waitForFunction(()=>document.querySelectorAll('#messages .bubble').length===6);
  await send(widget,'失败的搜索');
  await main.waitForFunction(()=>document.querySelector('#messages').textContent.includes('模拟搜索失败'),null,{timeout:5000});
  assert.match(await main.locator('#messages').textContent(),/失败的搜索/,'failed widget questions remain visible in the main transcript');
  assert.doesNotMatch(await main.locator('#messages').textContent(),/未完成的半句/);
  await main.reload();await main.waitForFunction(()=>document.querySelector('#messages').textContent.includes('模拟搜索失败'));
  await send(widget,'接口拒绝');
  await main.waitForFunction(()=>document.querySelector('#messages').textContent.includes('模型工具调用达到限制'));
  await send(main,'接口拒绝');
  await main.reload();await main.waitForFunction(()=>document.querySelectorAll('#messages .bubble').length>=12);
  assert.equal((await main.locator('#messages').textContent()).split('模型工具调用达到限制').length-1,2,'both entry points retain the original HTTP failure');
  await send(main,'失败后正常说话');
  assert.equal(submitted.at(-1).messages.some(m=>m.content.includes('失败的搜索')||m.content.includes('未完成的半句')||m.content.includes('接口拒绝')||m.content.includes('达到限制')),false);
  const pending=send(widget,'等待中的失败');
  for(let i=0;i<100&&!late;i++)await new Promise(r=>setTimeout(r,10));assert.ok(late);
  await main.locator('#clear-chat').click();late();await pending;
  await send(widget,'清空后重新开始');
  assert.deepEqual(submitted.at(-1).messages,[{role:'user',content:'清空后重新开始'}]);
  await main.waitForFunction(()=>document.querySelectorAll('#messages .bubble').length===2);
  await main.reload();await main.waitForFunction(()=>document.querySelectorAll('#messages .bubble').length===2);
  assert.equal(await main.locator('#messages').textContent().then(s=>s.includes('等待中的失败')||s.includes('模拟搜索失败')),false);
  late=undefined;const mainPending=send(main,'等待中的旧请求');
  for(let i=0;i<100&&!late;i++)await new Promise(r=>setTimeout(r,10));assert.ok(late);
  await widget.evaluate(async()=>{const {createChatHistory}=await import('./chat-history.js');const history=createChatHistory();await history.open('history-test');await history.clear();history.dispose();});
  late();await mainPending;await send(main,'第二次清空后');
  assert.deepEqual(submitted.at(-1).messages,[{role:'user',content:'第二次清空后'}],'clearing in another window also cancels a main-page request');
  assert.deepEqual(await widget.evaluate(()=>window.voiceCalls.filter(action=>['open','speak','synthesis','ttsStart','wakeOpen'].includes(action))),[],'history sync does not synthesize or start capture');
  assert.deepEqual(errors,[]);
});
