import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { chromium } from 'playwright';
import { startServers } from '../../../server/index.js';
import { SESSION_COOKIE } from '../../../server/accounts.js';

test('assistant custom provider drafts and saved keys survive switching and reload independently', async t => {
  const directory = await mkdtemp(path.join(tmpdir(), 'atb-assistant-profiles-'));
  const server = await startServers({lanIp:'127.0.0.1',httpsPort:0,httpPort:0,relayPort:0,publicOrigin:null,dataDir:path.join(directory,'data'),certDir:path.join(directory,'certs')});
  let browser;
  t.after(async () => { await browser?.close(); await server.close(); await rm(directory,{recursive:true,force:true}); });
  await server.accounts.setup('profile-test','fixture-password');
  const session = await server.accounts.login('profile-test','fixture-password');
  browser = await chromium.launch();
  const context = await browser.newContext({ignoreHTTPSErrors:true});
  await context.addCookies([{name:SESSION_COOKIE,value:session.token,domain:'127.0.0.1',path:'/',secure:true,httpOnly:true,sameSite:'Strict'}]);
  const page = await context.newPage(), errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.route('**/api/assistant/balance*',route=>route.fulfill({json:{kind:'unsupported'}}));
  await page.goto(`https://127.0.0.1:${server.secure.address().port}/modules/assistant/#model`);
  await page.locator('#workspace').waitFor({state:'visible'});
  await page.locator('#api-source').selectOption('custom');
  await page.locator('#base-url').fill('https://draft.example/v1');
  await page.locator('#api-key').fill('custom-fixture-key');
  await page.locator('#model').fill('custom-model');
  await page.locator('#protocol').selectOption('responses');
  await page.locator('#provider').selectOption('deepseek');
  assert.equal(await page.locator('#api-key').inputValue(),'');
  assert.equal(await page.locator('#protocol').inputValue(),'chat');
  await page.locator('#api-key').fill('deepseek-fixture-key');
  await page.locator('#model').fill('deepseek-chat');
  await page.locator('#provider').selectOption('custom');
  assert.equal(await page.locator('#api-key').inputValue(),'custom-fixture-key');
  assert.equal(await page.locator('#model').inputValue(),'custom-model');
  assert.equal(await page.locator('#protocol').inputValue(),'responses');
  await page.locator('#model-form [type=submit]').click();
  await page.waitForFunction(()=>document.querySelector('#model-result').textContent==='已保存');
  assert.equal(await page.evaluate(()=>window.atbHasUnsavedChanges()),true);
  await page.locator('#provider').selectOption('deepseek');
  assert.equal(await page.locator('#api-key').inputValue(),'deepseek-fixture-key');
  await page.locator('#model-form [type=submit]').click();
  await page.waitForFunction(()=>!window.atbHasUnsavedChanges());
  await page.reload(); await page.locator('#workspace').waitFor({state:'visible'});
  await page.locator('#provider').selectOption('custom');
  assert.equal(await page.locator('#api-key').inputValue(),'');
  assert.equal(await page.locator('#model').inputValue(),'custom-model');
  assert.match(await page.locator('#key-state').textContent(),/已保存/);
  await page.locator('#model-form [type=submit]').click();
  await page.waitForFunction(()=>!window.atbHasUnsavedChanges());
  assert.deepEqual(errors,[]);
});
